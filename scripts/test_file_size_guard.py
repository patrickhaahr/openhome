import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

GUARD = Path(__file__).resolve().parent.parent / "tools" / "git-file-size-guard"
OVERSIZED = b"line\n" * 4420
OVER_PIPE_BUFFER = b"line\n" * 40000
ENV = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")} | {
    "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_CONFIG_NOSYSTEM": "1",
}


class GuardRepo(unittest.TestCase):
    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.repo = Path(scratch.name) / "repo"
        self.repo.mkdir()
        self.git("init", "-q")
        self.guard = Path(scratch.name) / "guard"
        shutil.copy(GUARD, self.guard)

    def git(self, *args):
        return subprocess.run(["git", *args], cwd=self.repo, env=ENV, check=True, capture_output=True, text=True).stdout

    def write(self, path, data):
        target = self.repo / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)

    def set_limit(self, tokens):
        text, changed = re.subn(r"^max_tokens=\d+$", f"max_tokens={tokens}", self.guard.read_text(), flags=re.M)
        self.assertEqual(changed, 1)
        self.guard.write_text(text)

    def offenders(self, *args, cwd=None):
        run = subprocess.run(["bash", self.guard, *args], cwd=cwd or self.repo, env=ENV, capture_output=True, text=True)
        found = set(re.findall(r"^  (.+) \(~\d+ tokens\)$", run.stderr, flags=re.M))
        self.assertEqual(run.returncode, 1 if found else 0, run.stderr)
        if not found:
            self.assertEqual(run.stderr, "")
        return found


class SharedRules(GuardRepo):
    def test_limit_change_moves_the_commit_hook_and_the_tree_check_together(self):
        self.write("small.txt", b"line\n" * 20)
        self.git("add", ".")
        self.assertEqual((self.offenders(), self.offenders("--tree")), (set(), set()))
        self.set_limit(10)
        self.assertEqual((self.offenders(), self.offenders("--tree")), ({"small.txt"}, {"small.txt"}))

    def test_commit_hook_and_tree_check_agree_on_every_exemption(self):
        self.write(".gitattributes", b"plain.csv -file-size-guard\nvendored.c linguist-vendored\nblob.txt binary\n")
        for path in ("plain.csv", "vendored.c", "blob.txt", "vendor/x.c", "a.lock"):
            self.write(path, OVERSIZED)
        self.write("marked.txt", b"code generated by x\n" + OVER_PIPE_BUFFER)
        self.write("nul.bin", b"\0" + OVERSIZED)
        self.write("at-cap.txt", b"x" * 20000)
        (self.repo / "link.txt").symlink_to("over.txt")
        offending = {"over.txt", "a-é.txt", 'quo"te.txt', "[over]*.txt", "sub dir/over.txt", "0:over.txt", ":(top)over.txt"}
        for path in offending:
            self.write(path, OVERSIZED)
        self.git("add", ".")
        self.assertEqual(self.offenders(), offending)
        self.assertEqual(self.offenders("--tree"), offending)

    def test_submodules_are_not_files(self):
        self.write("over.txt", OVERSIZED)
        self.git("init", "-q", "module")
        self.git("-C", "module", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", "m")
        self.git("add", ".")
        self.assertIn("160000", self.git("ls-files", "--stage", "module"))
        self.assertEqual((self.offenders(), self.offenders("--tree")), ({"over.txt"}, {"over.txt"}))

    def test_both_entry_points_work_from_a_subdirectory(self):
        self.write("sub/over.txt", OVERSIZED)
        self.write(".gitattributes", b"")
        self.git("add", ".")
        sub = self.repo / "sub"
        self.assertEqual((self.offenders(cwd=sub), self.offenders("--tree", cwd=sub)), ({"sub/over.txt"}, {"sub/over.txt"}))


class TreeSelection(GuardRepo):
    def test_tracked_file_matched_by_gitignore_is_checked(self):
        self.write(".gitignore", b"*.log\n")
        self.write("tracked.log", OVERSIZED)
        self.write("untracked.log", OVERSIZED)
        self.git("add", "-f", "tracked.log")
        self.assertEqual(self.offenders("--tree"), {"tracked.log"})

    def test_untracked_file_is_checked_unless_info_exclude_ignores_it(self):
        self.write("excluded.txt", OVERSIZED)
        self.write("untracked.txt", OVERSIZED)
        (self.repo / ".git/info/exclude").write_text("excluded.txt\n")
        self.assertEqual(self.offenders("--tree"), {"untracked.txt"})

    def test_path_arguments_narrow_the_check_and_may_be_missing_or_ignored(self):
        self.write(".gitignore", b"ignored.txt\n")
        for path in ("one/over.txt", "two/over.txt", "ignored.txt"):
            self.write(path, OVERSIZED)
        self.assertEqual(self.offenders("--tree", "one", "missing", "ignored.txt"), {"one/over.txt"})
        self.assertEqual(self.offenders("--tree", "missing"), set())

    def test_tracked_file_deleted_from_the_working_tree_is_skipped(self):
        self.write("gone.txt", OVERSIZED)
        self.git("add", ".")
        (self.repo / "gone.txt").unlink()
        self.assertEqual(self.offenders("--tree"), set())

    def test_checking_writes_no_objects(self):
        self.write("over.txt", OVERSIZED)
        before = self.git("count-objects")
        self.offenders("--tree")
        self.assertEqual(self.git("count-objects"), before)

    def test_path_outside_the_repository_fails_instead_of_passing(self):
        run = subprocess.run(["bash", self.guard, "--tree", "../outside"], cwd=self.repo, env=ENV, capture_output=True)
        self.assertEqual(run.returncode, 128)


if __name__ == "__main__":
    unittest.main()
